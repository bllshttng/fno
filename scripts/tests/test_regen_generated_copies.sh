#!/usr/bin/env bash
# test_regen_generated_copies.sh - watch scripts/regen-generated-copies.py
# refuse the spliced notify_dispatch twin by name, and refuse to move a copy
# backwards from its source. The guard exists because a regen once rewrote
# the spliced twin with the owner's daemon bodies and shipped the damage.
set -uo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "${SCRIPT_DIR}/../.." && pwd)"
SCRIPT="$REPO_ROOT/scripts/regen-generated-copies.py"

PASS=0; FAIL=0
pass() { PASS=$((PASS+1)); printf '[rgc] PASS: %s\n' "$*"; }
fail() { FAIL=$((FAIL+1)); printf '[rgc] FAIL: %s\n' "$*" >&2; }

TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT

REGEN="cargo build --manifest-path crates/fno-agents/Cargo.toml"

# fixture DIR ONLY_GENERIC: the tree slice the regen walks. The spliced owner
# carries the two // @fno-copy: regions and its test module; the twin holds
# the spliced bytes a correct cargo build writes.
fixture() {
    local dir="$1" only_generic="$2"
    mkdir -p "$dir/crates/fno/src" "$dir/crates/fno-agents/src/event_store"
    printf 'event_types: []\n' > "$dir/crates/fno-agents/src/event_store/schema.yaml"
    {
        printf 'crates/fno/src/generic.rs\tcrates/fno-agents/src/generic.rs\t%s\n' "$REGEN"
        if [[ "$only_generic" != "only-generic" ]]; then
            printf 'crates/fno/src/notify_dispatch.rs\tcrates/fno-agents/src/notify_dispatch.rs\t%s\n' "$REGEN"
        fi
    } > "$dir/generated-artifacts.tsv"
    printf 'fn a() {}\n\n#[cfg(test)]\nmod tests {\n}\n' > "$dir/crates/fno-agents/src/generic.rs"
    : > "$dir/crates/fno-agents/src/notify_dispatch.rs"
    printf '// @generated by crates/fno-agents/build.rs from crates/fno-agents/src/notify_dispatch.rs. Do not edit.\nfn spliced() {}\n' \
        > "$dir/crates/fno/src/notify_dispatch.rs"
    printf '// stale twin\n' > "$dir/crates/fno/src/generic.rs"
}

# run_regen NAME WANT_EXIT DIR [NEEDLE...]
run_regen() {
    local name="$1" want="$2" dir="$3" needle out rc
    shift 3
    out="$(cd "$dir" && python3 "$SCRIPT" 2>&1)"; rc=$?
    if [[ $rc -ne $want ]]; then fail "$name: want exit $want got $rc ($out)"; return 1; fi
    for needle in "$@"; do
        if [[ "$out" != *"$needle"* ]]; then fail "$name: output lacks '$needle' ($out)"; return 1; fi
    done
    pass "$name"
}

# AC1: the spliced twin is refused by name, and a twin newer than its source
# that a rebuild would change is refused with no write. Both twins keep their
# bytes and the run fails.
fixture "$TMP/guard" with-notify
touch -t 202001010000 "$TMP/guard/crates/fno-agents/src/generic.rs"
touch -t 202101010000 "$TMP/guard/crates/fno/src/generic.rs"
touch -t 202001010000 "$TMP/guard/crates/fno-agents/src/notify_dispatch.rs"
touch -t 202101010000 "$TMP/guard/crates/fno/src/notify_dispatch.rs"
BEFORE_GENERIC="$(cat "$TMP/guard/crates/fno/src/generic.rs")"
BEFORE_NOTIFY="$(cat "$TMP/guard/crates/fno/src/notify_dispatch.rs")"
run_regen \
    "AC1: newer copies are refused with no write" 1 "$TMP/guard" \
    "is newer than its source crates/fno-agents/src/generic.rs" \
    "notify_dispatch.rs carries // @fno-copy: regions" \
    || true
AFTER_GENERIC="$(cat "$TMP/guard/crates/fno/src/generic.rs")"
AFTER_NOTIFY="$(cat "$TMP/guard/crates/fno/src/notify_dispatch.rs")"
if [[ "$BEFORE_GENERIC" == "$AFTER_GENERIC" && "$BEFORE_NOTIFY" == "$AFTER_NOTIFY" ]]; then
    pass "AC1: refused twins keep their bytes"
else
    fail "AC1: refused twins keep their bytes"
fi

# AC2: a source newer than its twin regenerates forward, and a second run
# finds the fresh bytes.
fixture "$TMP/forward" only-generic
touch -t 202001010000 "$TMP/forward/crates/fno/src/generic.rs"
touch -t 202101010000 "$TMP/forward/crates/fno-agents/src/generic.rs"
run_regen \
    "AC2: a source newer than its twin regenerates forward" 0 "$TMP/forward" \
    "rebuilt: crates/fno/src/generic.rs"
if [[ "$(cat "$TMP/forward/crates/fno/src/generic.rs")" == \
        "// @generated by crates/fno-agents/build.rs from crates/fno-agents/src/generic.rs. Do not edit.
fn a() {}" ]]; then
    pass "AC2: the rebuilt twin carries the header and drops the test module"
else
    fail "AC2: the rebuilt twin carries the header and drops the test module"
fi
run_regen \
    "AC2: a second run finds the fresh bytes" 0 "$TMP/forward" \
    "fresh: crates/fno/src/generic.rs"

printf '[rgc] RESULTS: %d passed, %d failed\n' "$PASS" "$FAIL"
[[ $FAIL -eq 0 ]]
