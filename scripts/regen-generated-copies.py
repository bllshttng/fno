#!/usr/bin/env python3
"""Rebuild the plain-copy Rust twins without a compile.

crates/fno/src/*.rs twins are generated by crates/fno-agents/build.rs as a
header line plus the source, which ties a twin refresh to `cargo build`. A
session under a build freeze cannot run that, so this script reproduces the
same bytes from generated-artifacts.tsv: CRLF normalized, the owner's test
module stripped, one header line, trailing newline. CI's generated-copies
step stays the proof - it rebuilds with cargo and `git diff --exit-code`s
the result.

Handled shapes (matching build.rs):
- a file ending in "\n#[cfg(test)]\nmod tests;\n" loses that suffix
  (sync_event_store)
- a file carrying "\n#[cfg(test)]\nmod tests {" splits there
  (sync_module_copy)
- neither marker feeds over verbatim (observation.rs, validate.rs)
- a .toml row feeds over byte for byte (sync_harness_capabilities and
  sync_registry_schema pass the source bytes straight through; no shape
  logic exists to reproduce)
- events_schema.json is the compact, key-sorted JSON projection of
  schema.yaml (sync_events_schema); its crates/fno twin is a byte copy

Everything else is refused by name: otel_read.rs embeds the OTEL schema via
a Rust Debug literal (build-only), and the codegen and doc rows
have their own generators.
"""

import json
import os
import re
import tempfile

TEST_DECL_SUFFIX = "\n#[cfg(test)]\nmod tests;\n"
TEST_MODULE_MARKER = "\n#[cfg(test)]\nmod tests {"
TSV = "generated-artifacts.tsv"
REGEN_NEEDLE = "cargo build --manifest-path crates/fno-agents/Cargo.toml"


def rows():
    for line in open(TSV, encoding="utf-8"):
        if line.startswith("#") or not line.strip():
            continue
        cols = line.rstrip("\n").split("\t")
        if len(cols) == 3 and cols[2] == REGEN_NEEDLE and cols[0].endswith(".rs"):
            yield cols[0], cols[1]


#: The sources build.rs copies VERBATIM (sync_harness_capabilities and
#: sync_registry_schema pass the bytes straight to write_if_different). Rows
#: are matched on the source, never on the extension: events_limits.toml is
#: also a .toml row with the same regen command, but build.rs generates it
#: from schema.yaml with shape logic a blind byte copy would destroy.
BYTE_COPY_SOURCES = (
    "crates/fno-agents/src/harness_capabilities.toml",
    "crates/fno-agents/src/registry_schema.toml",
    "crates/fno-agents/src/event_store/events_schema.json",
)

EVENTS_SCHEMA_SOURCE = "cli/src/fno/events/schema.yaml"
EVENTS_SCHEMA_COPY = "crates/fno-agents/src/event_store/events_schema.json"
EVENTS_SCHEMA_MARKER = (
    "GENERATED by crates/fno-agents/build.rs from cli/src/fno/events/schema.yaml. "
    "Do not edit; rebuild instead."
)


def _seq(v):
    """build.rs seq_to_json: scalars pass, anything else becomes null."""
    if not isinstance(v, list):
        return []
    return [i if isinstance(i, (bool, int, float, str)) else None for i in v]


def _at(d, *keys):
    for k in keys:
        if not isinstance(d, dict):
            return None
        d = d.get(k)
    return d


def _int_or(v, default):
    return v if isinstance(v, int) and not isinstance(v, bool) else default


def events_schema_projection(text):
    """Reproduce build.rs sync_events_schema byte for byte.

    serde_yaml_ng reads YAML 1.2, where `off` and `yes` are strings, so the
    loader keeps only the true/false booleans. serde_json without
    preserve_order sorts keys and writes compact output with no newline.
    """
    try:
        import yaml
    except ImportError:
        raise SystemExit(
            "events_schema.json needs PyYAML: uv run --project cli python "
            "scripts/regen-generated-copies.py"
        )

    class Yaml12Loader(yaml.SafeLoader):
        pass

    bool_tag = "tag:yaml.org,2002:bool"
    Yaml12Loader.yaml_implicit_resolvers = {
        k: [(tag, rx) for tag, rx in v if tag != bool_tag]
        for k, v in yaml.SafeLoader.yaml_implicit_resolvers.items()
    }
    Yaml12Loader.add_implicit_resolver(
        bool_tag, re.compile(r"^(?:true|True|TRUE|false|False|FALSE)$"), list("tTfF")
    )
    parsed = yaml.load(text, Loader=Yaml12Loader)
    event_types = {}
    for entry in parsed.get("event_types") or []:
        name = entry.get("name") if isinstance(entry, dict) else None
        if not isinstance(name, str):
            continue
        data = entry.get("data")
        enums = {}
        for field, prop in (_at(data, "properties") or {}).items():
            if not isinstance(field, str):
                continue
            if isinstance(_at(prop, "enum"), list):
                enums[field] = _seq(prop["enum"])
            for sub, subprop in (_at(prop, "items", "properties") or {}).items():
                if isinstance(sub, str) and isinstance(_at(subprop, "enum"), list):
                    enums[f"{field}[].{sub}"] = _seq(subprop["enum"])
        event_types[name] = {
            "sources": _seq(entry.get("sources")),
            "required": _seq(_at(data, "required")),
            "forbidden": _seq(_at(data, "forbidden")),
            "enums": enums,
        }
    family = parsed.get("protocol_family")
    projection = {
        "envelope_required": _seq(_at(parsed, "envelope", "required")),
        "events_schema_marker": EVENTS_SCHEMA_MARKER,
        "allowed_sources": _seq(_at(parsed, "envelope", "properties", "source", "enum")),
        "source_patterns": _seq(_at(parsed, "envelope", "properties", "source", "patterns")),
        "max_data_bytes": _int_or(_at(parsed, "limits", "max_data_bytes"), 65536),
        "gates": _seq(parsed.get("gates")),
        "protocol_family": {
            "types": _seq(_at(family, "types")),
            "version": _int_or(_at(family, "version"), 1),
            "envelope_allowed": _seq(_at(family, "envelope", "allowed")),
            "envelope_required": _seq(_at(family, "envelope", "required")),
            "outcome_enum": _seq(_at(family, "outcome", "enum")),
            "outcome_present_on": _seq(_at(family, "outcome", "present_on")),
        },
        "event_types": event_types,
    }
    return json.dumps(projection, sort_keys=True, separators=(",", ":"), ensure_ascii=False)


def byte_copy_rows():
    """The mirrors build.rs copies byte for byte. A byte copy needs no
    build: the regen IS the copy, so a frozen session commits a fresh
    mirror the same way CI later proves it."""
    for line in open(TSV, encoding="utf-8"):
        if line.startswith("#") or not line.strip():
            continue
        cols = line.rstrip("\n").split("\t")
        if len(cols) == 3 and cols[2] == REGEN_NEEDLE and cols[1] in BYTE_COPY_SOURCES:
            yield cols[0], cols[1]


def rebuilt_text(source_rel, text):
    text = text.replace("\r\n", "\n")
    if source_rel == "crates/fno-agents/src/otel_read.rs":
        return None, (
            "otel_read.rs embeds otel_schema.sql as a Rust Debug literal; "
            "regenerate it with cargo build"
        )
    header = f"// @generated by crates/fno-agents/build.rs from {source_rel}. Do not edit.\n"
    if text.endswith(TEST_DECL_SUFFIX):
        body = text[: -len(TEST_DECL_SUFFIX)].rstrip("\n")
        return f"{header}{body}\n", None
    if TEST_MODULE_MARKER in text:
        marker_count = text.count(TEST_MODULE_MARKER)
        if marker_count != 1:
            return None, (
                f"{source_rel} carries {marker_count} test-module markers; "
                "build.rs expects exactly one"
            )
        body = text.split(TEST_MODULE_MARKER, 1)[0].rstrip("\n")
        return f"{header}{body}\n", None
    return f"{header}{text}", None


def write_if_different(path, out_text):
    existing = open(path, encoding="utf-8").read() if os.path.isfile(path) else None
    if existing == out_text:
        print(f"fresh: {path}")
        return
    fd, temp = tempfile.mkstemp(dir=os.path.dirname(path) or ".")
    with os.fdopen(fd, "w", encoding="utf-8", newline="") as fh:
        fh.write(out_text)
    os.replace(temp, path)
    print(f"rebuilt: {path}")


def main():
    # The projection runs first: the crates/fno twin byte-copies its output.
    schema_text = open(EVENTS_SCHEMA_SOURCE, encoding="utf-8").read()
    write_if_different(EVENTS_SCHEMA_COPY, events_schema_projection(schema_text))
    pairs = [(copy, source, False) for copy, source in byte_copy_rows()]
    pairs += [(copy, source, True) for copy, source in rows()]
    if not pairs:
        raise SystemExit(f"no plain-copy rows found in {TSV}")
    refusals = []
    for copy_rel, source_rel, shaped in pairs:
        text = open(source_rel, encoding="utf-8").read()
        if not shaped:
            write_if_different(copy_rel, text)
            continue
        out_text, refusal = rebuilt_text(source_rel, text)
        if refusal:
            refusals.append(refusal)
            print(f"refused: {refusal}")
            continue
        write_if_different(copy_rel, out_text)
    if refusals:
        raise SystemExit(1)


if __name__ == "__main__":
    main()
