#!/usr/bin/env python3
"""Rebuild the plain-copy Rust twins without a compile.

crates/fno/src/*.rs twins are generated by crates/fno-agents/build.rs as a
header line plus the source, which ties a twin refresh to `cargo build`. A
session under a build freeze cannot run that, so this script reproduces the
same bytes from generated-artifacts.tsv: CRLF normalized, the owner's test
module stripped, one header line, trailing newline. CI's generated-copies
step stays the proof - it rebuilds with cargo and `git diff --exit-code`s
the result.

Handled shapes (matching build.rs):
- a file ending in "\n#[cfg(test)]\nmod tests;\n" loses that suffix
  (sync_event_store)
- a file carrying "\n#[cfg(test)]\nmod tests {" splits there
  (sync_module_copy)
- neither marker feeds over verbatim (observation.rs, validate.rs)

Everything else is refused by name: otel_read.rs embeds the OTEL schema via
a Rust Debug literal (build-only), and the schema, codegen, doc, and
byte-copy rows have their own generators.
"""

import os
import tempfile

TEST_DECL_SUFFIX = "\n#[cfg(test)]\nmod tests;\n"
TEST_MODULE_MARKER = "\n#[cfg(test)]\nmod tests {"
TSV = "generated-artifacts.tsv"
REGEN_NEEDLE = "cargo build --manifest-path crates/fno-agents/Cargo.toml"


def rows():
    for line in open(TSV, encoding="utf-8"):
        if line.startswith("#") or not line.strip():
            continue
        cols = line.rstrip("\n").split("\t")
        if len(cols) == 3 and cols[2] == REGEN_NEEDLE and cols[0].endswith(".rs"):
            yield cols[0], cols[1]


def rebuilt_text(source_rel, text):
    text = text.replace("\r\n", "\n")
    if source_rel == "crates/fno-agents/src/otel_read.rs":
        return None, (
            "otel_read.rs embeds otel_schema.sql as a Rust Debug literal; "
            "regenerate it with cargo build"
        )
    header = f"// @generated by crates/fno-agents/build.rs from {source_rel}. Do not edit.\n"
    if text.endswith(TEST_DECL_SUFFIX):
        body = text[: -len(TEST_DECL_SUFFIX)].rstrip("\n")
        return f"{header}{body}\n", None
    if TEST_MODULE_MARKER in text:
        marker_count = text.count(TEST_MODULE_MARKER)
        if marker_count != 1:
            return None, (
                f"{source_rel} carries {marker_count} test-module markers; "
                "build.rs expects exactly one"
            )
        body = text.split(TEST_MODULE_MARKER, 1)[0].rstrip("\n")
        return f"{header}{body}\n", None
    return f"{header}{text}", None


def write_if_different(path, out_text):
    existing = open(path, encoding="utf-8").read() if os.path.isfile(path) else None
    if existing == out_text:
        print(f"fresh: {path}")
        return
    fd, temp = tempfile.mkstemp(dir=os.path.dirname(path) or ".")
    with os.fdopen(fd, "w", encoding="utf-8", newline="") as fh:
        fh.write(out_text)
    os.replace(temp, path)
    print(f"rebuilt: {path}")


def main():
    pairs = list(rows())
    if not pairs:
        raise SystemExit(f"no plain-copy .rs rows found in {TSV}")
    refusals = []
    for copy_rel, source_rel in pairs:
        out_text, refusal = rebuilt_text(source_rel, open(source_rel, encoding="utf-8").read())
        if refusal:
            refusals.append(refusal)
            print(f"refused: {refusal}")
            continue
        write_if_different(copy_rel, out_text)
    if refusals:
        raise SystemExit(1)


if __name__ == "__main__":
    main()
